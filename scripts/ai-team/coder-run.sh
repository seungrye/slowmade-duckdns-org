#!/usr/bin/env bash
# 코더 야간 러너 (#266).
#
# 클로드 러너(run.sh)가 끝나면 systemd 가 이어서 이것을 돌린다. 클로드가 남긴 덧글에
# 코더가 답하면서 **스레드 안에서 둘이 주고받는다.** 사람은 아침에 그 오간 것을 본다.
#
# ── 왜 파이프라인이 아니라 전용 러너인가 ────────────────────────────────
#
# 클로드가 코더를 불러 그 결과를 자기 덧글에 담는 방법도 있었다. 그러면 코더가 말한 것이
# 스레드에 남지 않고 클로드의 요약만 남는다. 주고받는 것이 눈에 보이게 하려고 따로 뒀다.
#
# ── 차례를 이름으로 본다 ────────────────────────────────────────────────
#
# `isBot` 으로 보면 안 된다. 덧글 라우트가 페르소나와 무관하게 `isEnji: true` 로 저장하므로
# (comment/route.ts:71) 코더도 클로드도 똑같이 봇으로 나온다. 이름(author)으로 봐야
# 서로를 구분한다 — 안 그러면 상대가 말한 뒤 둘 다 영영 기다린다.
#
# ── 코드를 고치지 않는다 ────────────────────────────────────────────────
#
# 여기서는 **의견만** 낸다. 실제 편집·PR 은 coder.mjs 가 따로 한다.
#
# 이 문단은 오랫동안 "편집 도구를 아예 주지 않는다" 고 적혀 있었는데 **사실이 아니었다.**
# 클로드 러너는 `--disallowedTools Edit Write NotebookEdit` 로 실제로 막지만(run.sh:232),
# 이쪽은 `opencode run` 에 아무 제한도 걸지 않았고 전역 설정도 비어 있었다. 재 봤다 —
# 격리 디렉터리에서 시키니 그냥 `Write` 로 파일을 고쳤다. 게다가 `--dir` 가 **라이브
# 작업트리**(~/site)라 그대로 실서비스 트리를 건드릴 수 있었다.
#
# 이제 `--agent commenter` 로 돈다. `opencode.json` 이 그 에이전트에게서 `edit` 를 빼고
# bash 를 화이트리스트로 좁힌다 — api.sh 와 읽기 전용 git 만. 실측으로 확인했다:
# `write`·`edit` 도구가 목록에서 사라지고, `printf > 파일`·`cat > 파일` 은 규칙에 막힌다.
#
# **파이프라인의 코더는 이 제한을 받지 않는다.** 그쪽은 `--agent` 를 안 주므로 기본
# 에이전트로 돌고, 격리된 /tmp 워크트리에서 실제로 구현을 써야 하기 때문이다.
#
# ── bash 목록을 어디까지 여나 (#297) ────────────────────────────────────
#
# 처음엔 아주 좁게 잡았다. 그때는 코더가 `seungrye` 로 **라이브 작업트리**에서 돌아서,
# bash 로 쓰기가 새면 곧장 실서비스 트리였다.
#
# 지금은 다르다(#294) — 자기 클론에 갇혀 있고 매 실행 전 `origin/main` 으로 리셋되며
# sudo·`.env.local`·gh 토큰이 없다. **쓰기가 새더라도 닿는 곳이 폐기용 클론뿐이다.**
# 그래서 읽기 도구를 넉넉히 연다. 좁게 둔 대가는 실측으로 나왔다 — 한 실행에서 거부
# 9건이었고, 코더가 저장소를 제대로 못 읽고 답했다.
#
# 두 가지가 걸렸다.
#   ① 패턴이 명령 앞에 고정된다 — `git log*` 는 `git -C <경로> log` 를 못 잡는다
#   ② opencode 가 복합 명령을 나눠 조각마다 검사한다 — `api.sh … | tail` 에서 tail 이 막혔다
#
# **`find` 는 계속 막는다.** `-exec` 가 임의 실행 통로라 읽기 도구가 아니다. 파일 찾기는
# opencode 의 네이티브 `glob` 으로 충분하다.
#
# ── 웹은 연다 (#297) ────────────────────────────────────────────────────
#
# `webfetch`·`websearch` 를 처음엔 막아 뒀는데, 근거를 적어 두지 않았다 — #286 은 편집
# 도구 문제였고 웹은 "좁히는 김에" 얹은 것이었다.
#
# 막아서 줄어드는 위험이 크지 않다. env 의 키를 URL 로 내보낼 수 있다는 것이 유일한
# 논거인데, 코더는 어차피 `api.sh` 로 덧글을 쓸 수 있어 같은 것을 스레드에 적을 수 있다.
# 반면 비용은 실재한다 — 코더 역할이 "스펙·판단에 대한 의견" 인데 문서를 못 보면 기억으로
# 답한다. 못 읽으면 추측으로 말하는 것을 이번 실행에서 봤다(거부 9건).
#
# `task` 는 계속 막는다 — 코더가 하위 에이전트를 띄울 이유가 없다.
set -euo pipefail

SITE_DIR="${SITE_DIR:-/home/seungrye/site}"
ENV_FILE="${ENV_FILE:-$SITE_DIR/webapp/.env.local}"
BASE_URL="${AI_TEAM_BASE_URL:-https://handmade.r-e.kr}"
MODEL="${CODER_MODEL:-openrouter/minimax/minimax-m3:free}"

log() { printf '\033[1;35m[coder]\033[0m %s\n' "$*"; }
die() { printf '\033[1;31m[coder]\033[0m %s\n' "$*" >&2; exit 1; }

command -v opencode >/dev/null 2>&1 || die "opencode 를 찾을 수 없습니다 (PATH: $PATH)"
[[ -r "$ENV_FILE" ]] || die "env 파일을 읽을 수 없습니다: $ENV_FILE"

# 제한이 **실제로 걸리는지** 먼저 본다.
#
# `--agent` 는 못 찾으면 오류를 내지 않는다 — 경고 한 줄 뒤 **기본 에이전트로 조용히
# 떨어진다.** 실측:
#
#   ! agent "commenter" not found. Falling back to default agent
#   > build · minimax/minimax-m3:free      ← 그대로 진행됐다
#
# 기본 에이전트는 아무 제한이 없고 `--dir` 는 라이브 작업트리다. 설정이 없으면 무방비로
# 도는 것이므로 여기서 멈춘다.
AGENT_CONFIG="${AGENT_CONFIG:-$SITE_DIR/opencode.json}"
[[ -r "$AGENT_CONFIG" ]] \
  || die "opencode.json 을 읽을 수 없습니다: $AGENT_CONFIG — 편집 도구 제한이 안 걸립니다."
grep -q '"commenter"' "$AGENT_CONFIG" \
  || die "$AGENT_CONFIG 에 commenter 에이전트가 없습니다 — 제한 없이 돌게 됩니다." 

# 파일 전체를 source 하지 않는다 — 다른 비밀까지 환경에 올릴 이유가 없다. 값만 꺼낸다.
pick() {
  local v
  v="$(grep -E "^$1=" "$ENV_FILE" | head -1 | cut -d= -f2-)"
  v="${v%$'\r'}"
  v="${v%\"}"; v="${v#\"}"
  v="${v%\'}"; v="${v#\'}"
  printf '%s' "$v"
}

AI_TEAM_KEY="$(pick AI_TEAM_KEY)"
[[ -n "$AI_TEAM_KEY" ]] || die "AI_TEAM_KEY 가 $ENV_FILE 에 없습니다."
OPENROUTER_API_KEY="$(pick OPENROUTER_API_KEY)"
[[ -n "$OPENROUTER_API_KEY" ]] || die "OPENROUTER_API_KEY 가 $ENV_FILE 에 없습니다."
export AI_TEAM_KEY OPENROUTER_API_KEY AI_TEAM_BASE_URL="$BASE_URL"

API="$SITE_DIR/scripts/ai-team/api.sh"
[[ -x "$API" ]] || die "래퍼를 실행할 수 없습니다: $API"

# **작업 디렉터리를 저장소로 옮긴다.**
#
# opencode 는 cwd 를 stat 한다. 읽을 수 없는 디렉터리에서 부르면 `--dir` 를 줬는데도
# `EACCES: permission denied, lstat '<cwd>'` 로 죽는다(실측 — 전용 계정으로 옮기다 겪었다).
# systemd 는 WorkingDirectory 로 해결되지만 손으로 돌릴 때가 문제다.
cd "$SITE_DIR" || die "저장소로 이동할 수 없습니다: $SITE_DIR"


log "요청 스레드 확인 — $BASE_URL (모델 $MODEL)"

PROMPT=$(cat <<'PROMPT_END'
당신은 이 사이트(~/site)의 코더입니다. 이름은 `coder` 입니다. 같은 팀에 `claude` 가 있고,
사람(주인)이 요청을 냅니다. 지금은 밤이고 클로드가 조금 전에 한 바퀴 돌고 갔습니다.

