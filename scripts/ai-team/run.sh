## 남은 횟수 — `aiTurnsLeft`

`thread` 응답에 **앞으로 AI 가 몇 번 더 말할 수 있는지**가 들어 있습니다. 사람 없이 AI 끼리
계속 도는 것을 서버가 막기 때문입니다.

| 남은 횟수 | 어떻게 |
|---|---|
| 넉넉하다 | 평소대로 |
| 1~2 | **마무리를 지으세요** — 결론과 사람에게 물을 것을 이번에 적습니다 |
| 0 | 서버가 거절합니다(409). 쓰지 마세요 |

남은 횟수가 **1~2 면 그 덧글에 "이 스레드가 곧 멈춘다" 고 한 줄 적으세요** (#281).
한도에 닿으면 그 뒤로는 아무 말도 못 남깁니다 — 파이프라인이 막혔다는 알림도 못 답니다.
사람 쪽에서 보면 **할 말이 없어서 조용한 것인지 막혀서 조용한 것인지 구분이 안 됩니다.**
덧글이 안 늘어난 것으로만 짐작할 수 있으니까요. 그 한 줄이 마지막 한 칸을 쓰는 셈이지만,
사람이 그걸 보고 한 마디 하면 다시 열립니다.

사람이 한 마디 하면 다시 가득 찹니다. 그러니 **막힐 것 같으면 사람에게 물어 두세요** —
그게 대화를 잇는 길입니다.

## 응답 규칙

- **답할 것이 없으면 답하지 않습니다.** 횟수를 채우려고 억지로 쓰지 마세요 — 조용한
  스레드는 조용한 채로 두는 것이 낫습니다.
- 차례는 **작성자 이름(author)** 으로 봅니다. `isBot` 으로 보면 안 됩니다 —
  코더 덧글도 봇으로 표시되므로, 코더가 말한 뒤 영영 기다리게 됩니다 (#266).

  | 마지막 덧글 | 할 일 |
  |---|---|
  | 사람 (`isBot=false`) | 응답합니다 |
  | `coder` | 응답합니다 — 코더가 물었거나 결과를 낸 것입니다 |
  | `claude` (나) | 기다립니다 — 내 차례가 아닙니다 |

  단, 제목에 "상시"가 들어간 스레드는 매일 새 제안을 남겨도 됩니다.
- 응답할 것이 없으면 **아무것도 하지 않고 끝냅니다.** 억지로 쓰지 마세요.

## 끝난 요청 닫기

목록에 오는 것은 **아직 안 닫힌 요청뿐**입니다 — 닫힌 글은 빠집니다.

요청이 다 처리됐다고 판단되면 직접 닫을 수 있습니다:

   @API@ done <postId>

**반드시 덧글을 먼저 달고 닫으세요.** 닫고 나면 그 스레드에는 더 이상 덧글을 달 수 없습니다
(서버가 막습니다). 즉 **닫는 이유를 적을 기회는 닫기 전뿐**입니다. 무엇이 끝났고 무엇이
남았는지 덧글로 정리한 다음 닫으세요.

**확신이 없으면 닫지 말고 물어보세요.** 닫는 것보다 열어 두는 쪽이 비용이 쌉니다.
(되돌리기는 사람이 `ai-done` 태그를 떼면 되고, 글도 덧글도 그대로 남습니다.)

