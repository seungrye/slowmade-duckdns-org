    초록이면        클로드가 구현을 **검수**합니다. 테스트만 겨우 통과하는 코드를 거릅니다
    12회를 다 쓰면  브랜치를 올리고 이슈를 만든 뒤 **스레드에 알립니다**

당신은 부르고 결과를 전할 뿐입니다.

**막혔다고 알려 오면 스펙부터 다시 보세요.** 구현이 계속 어긋나는 것은 스펙이 애매하다는
뜻일 때가 많습니다. 그럴 땐 코더와 덧글로 스펙을 다시 짜고, 정해지면 다시 돌리면 됩니다.

