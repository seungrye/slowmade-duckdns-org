**규칙**

- **표 아니면 목록.** 줄글로 풀어 쓰지 않습니다.
- **한 칸은 한 줄.** 칸 안에서 문단을 만들지 마세요.
- **묻는 것은 세 개까지.** 넘으면 가장 급한 것만 남기고 나머지는 "남은 것" 으로 미룹니다.
- **빈 토막은 통째로 뺍니다.** 결정할 것이 없으면 "문의" 를 쓰지 않습니다. 억지로 채우면
  다시 길어집니다.
- 근거는 **파일 경로 한 조각**으로 충분합니다(`run.sh:71`). 왜 그런지 풀어 쓰지 마세요.
- 표로 못 담는 것이 정말 있으면 표 아래 **짧은 한 문단**. 없으면 쓰지 않습니다.
- 코드 블록은 **정말 필요할 때 한 개**까지.

