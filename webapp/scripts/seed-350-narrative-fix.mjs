#!/usr/bin/env node
// scripts/seed-350-narrative-fix.mjs - #350's further scenario work.
//
// The outside reviewer's second set of points (P0 plus P1 option B):
//   P0: station_path_steel's derail branch means 'a forced stop or seizure' rather than 'a derailment'.
//       That resolves the contradiction with climax_revolution_path's *use of an intact train* afterwards.
//   P1: omphalos_infiltration's onFailure was kael_caught_minor.
//       Being 'Kael's discovery scene', it confused identity when *Rin or Solwen* entered.
//       A new omphalos_caught_at_gate is added - a discovery scene with a neutral subject.
//
// Both changes are idempotent: findOneAndUpdate \$set / upsert.
// The illustration guard applies (a real URL is preserved).

import mongoose from 'mongoose';

async function main() {
  await mongoose.connect(process.env.MONGO_URI);
  const Scene = mongoose.model(
    'S',
    new mongoose.Schema({}, { strict: false, collection: 'webadventurescenes' }),
  );

  // -- P0: station_path_steel - updating the derail/hijack labels ---------
  const sp = await Scene.findOne({ id: 'station_path_steel' }).lean();
  if (sp) {
    const newChoices = sp.choices.map((c) => {
      if (c.id === 'derail') {
        return {
          ...c,
          label:
            '[완력] 선로 전환기를 *강제 고정* — 열차를 정거장에 *강제 정차* 시켜 *나포* 한다.',
        };
      }
      if (c.id === 'hijack') {
        return {
          ...c,
          label: '[지능] 제어실을 해킹 — 열차의 제어권을 *온전히* 빼앗는다.',
        };
      }
      return c;
    });
    await Scene.findOneAndUpdate(
      { id: 'station_path_steel' },
      { $set: { choices: newChoices } },
    );
    console.log('updated: station_path_steel — derail/hijack 라벨 갱신');
  }

  // -- P1: adding omphalos_caught_at_gate --------------------------------
  // The ending_petrification scene itself was deleted in #327 (handled as an automatic ending).
  // That left plain.to dangling - so this scene itself is made *isEnding=true with endingId=petrification*
  // and treated as *an ending on entry*. It follows on from the body's *being dragged away* mood.
  const NEW_SCENE = {
    id: 'omphalos_caught_at_gate',
    illustration: '/web-adventure/scenes/placeholder-square.svg',
    title: 'Scene 06i-fail — 게이트의 손',
    body: [
      '옴팔로스 게이트의 경비병이 *너의 팔* 을 잡았다. *위조 시민증* 이 손에서 떨어진다.',
      '"사제단의 정제소로 — 산 채로 인계되는 마지막 가솔린."',
      '너의 외투 안 *인장* / *권총* / *깃털* 도 — 모두 빼앗긴다. 너는 묶인 채 *호송 열차의 화물칸* 으로 끌려간다.',
    ],
    choices: [],
    isEnding: true,
    endingId: 'petrification',
    onEnter: { hpDelta: -5, stigmaDelta: 4 },
  };
  const curGate = await Scene.findOne({ id: NEW_SCENE.id }).lean();
  const update = { ...NEW_SCENE };
  // The illustration guard - a real URL generated by painter is kept.
  if (curGate && curGate.illustration && !curGate.illustration.includes('placeholder')) {
    update.illustration = curGate.illustration;
  }
  await Scene.findOneAndUpdate({ id: NEW_SCENE.id }, update, { upsert: true, new: true });
  console.log('upsert:', NEW_SCENE.id);

  // -- reassigning omphalos_infiltration.onFailure -----------------------
  const inf = await Scene.findOne({ id: 'omphalos_infiltration' }).lean();
  if (inf) {
    const newInfChoices = inf.choices.map((c) => {
      if (c.onFailure === 'kael_caught_minor') {
        return { ...c, onFailure: 'omphalos_caught_at_gate' };
      }
      return c;
    });
    await Scene.findOneAndUpdate(
      { id: 'omphalos_infiltration' },
      { $set: { choices: newInfChoices } },
    );
    console.log('updated: omphalos_infiltration — onFailure (kael_caught_minor → omphalos_caught_at_gate)');
  }

  await mongoose.disconnect();
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
