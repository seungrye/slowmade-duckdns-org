export function getEndingMeta(endingId: string): EndingMeta {
  return (
    endingsMeta[endingId as EndingId] ?? {
      title: `엔딩 — ${endingId}`,
      epilogue: "알 수 없는 결말.",
      icon: "❓",
      aftermath: "— 다음 이야기는 너에게 달려 있다.",
    }
  );
}
